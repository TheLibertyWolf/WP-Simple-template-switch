function po_quote(string $value): string
{
    return '"' . addcslashes($value, "\\\"\n\r\t") . '"';
}

$language_dir = dirname(__DIR__) . '/languages';

foreach ($locales as $locale => $metadata) {
    $header = [
        'Project-Id-Version: WP Simple Template Switch 2.0.0',
        'Report-Msgid-Bugs-To: https://github.com/TheLibertyWolf/WP-Simple-template-switch/issues',
        'POT-Creation-Date: 2026-08-16 14:04+0200',
        'PO-Revision-Date: 2026-08-16 14:10+0200',
        'Last-Translator: SAS Jessy System <contact@jessysystem.com>',
        'Language-Team: ' . $metadata['team'],
        'Language: ' . $locale,
        'MIME-Version: 1.0',
        'Content-Type: text/plain; charset=UTF-8',
        'Content-Transfer-Encoding: 8bit',
        'Plural-Forms: ' . $metadata['plural'],
        'X-Generator: WP Simple Template Switch translation builder',
    ];

    $contents = "# WP Simple Template Switch translation.\n";
    $contents .= "# Copyright (C) 2026 SAS Jessy System\n";
    $contents .= "# This file is distributed under the GPL-2.0-or-later license.\n";
    $contents .= "msgid \"\"\nmsgstr \"\"\n";
    foreach ($header as $line) {
        $contents .= po_quote($line . "\n") . "\n";
    }

    foreach ($translations as $source => $localized) {
        $translation = $metadata['index'] === null ? $source : $localized[$metadata['index']];
        $contents .= "\nmsgid " . po_quote($source) . "\n";
        $contents .= "msgstr " . po_quote($translation) . "\n";
    }

    $forms = $plural['translations'][$locale];
    $contents .= "\n#, php-format\n";
    $contents .= "msgid " . po_quote($plural['singular']) . "\n";
    $contents .= "msgid_plural " . po_quote($plural['plural']) . "\n";
    $contents .= "msgstr[0] " . po_quote($forms[0]) . "\n";
    $contents .= "msgstr[1] " . po_quote($forms[1]) . "\n";

    $path = $language_dir . '/wp-simple-template-switch-' . $locale . '.po';
    if (file_put_contents($path, $contents) === false) {
        throw new RuntimeException('Unable to write ' . $path);
    }
}

fwrite(STDOUT, sprintf("Built %d translations for %d locales.\n", count($translations) + 1, count($locales)));
